// Generates website/js/data.js (merchant brands + category keyword rules) from the shared TypeScript lists,
// so the website's live SMS demo recognises the same merchants as the apps.
// Run: node scripts/gen-website-data.mjs
import { readFileSync, writeFileSync } from 'node:fs';

const brandsTs = readFileSync('src/features/merchants/brands.ts', 'utf8');
const narrationTs = readFileSync('src/features/import/narration.ts', 'utf8');

const brands = [];
for (const m of brandsTs.matchAll(/^\s*b\((\/.*?\/i), (?:'([^']+)'|"([^"]+)"), '(#[0-9A-Fa-f]{6})'(?:, (?:'([^']+)'|null))?\),?$/gm)) {
  brands.push(`  [${m[1]}, ${JSON.stringify(m[2] ?? m[3])}, ${JSON.stringify(m[4])}]`);
}
const block = narrationTs.match(/const CATEGORY_RULES[^=]*= \[([\s\S]*?)\n\];/);
if (!brands.length || !block) throw new Error('Could not read brands or category rules');
const rules = [...block[1].matchAll(/\[(\/.*?\/i), '([^']+)'\]/g)].map((m) => `  [${m[1]}, ${JSON.stringify(m[2])}]`);

writeFileSync('website/js/data.js', `// Generated by scripts/gen-website-data.mjs from src/features/merchants/brands.ts and src/features/import/narration.ts. Do not edit.
globalThis.PaisaData = {
brands: [
${brands.join(',\n')}
],
categoryRules: [
${rules.join(',\n')}
],
};
`);
console.log(`brands ${brands.length}, rules ${rules.length}`);
